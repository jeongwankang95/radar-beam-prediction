"""Fig. 3: forest plot of the paper's link-level contrasts, generated from the bootstrap results (results/analysis, else
results/reference; no number typed by hand). Writes the figure's TikZ file.
Usage: python figures/make_forest.py OUT.tex [width_cm] [--no-letters]"""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "analysis"))
from paths import output_or_reference

OUT = sys.argv[1]
WIDTH = float(sys.argv[2]) if len(sys.argv) > 2 and not sys.argv[2].startswith("--") else 8.6  # picture width, cm
LETTERS = "--no-letters" not in sys.argv


def boot(f):
    d = json.load(open(output_or_reference(f)))["deltas"]["dB recovered (ref-new)"]
    return d["point"], d["lo"], d["hi"]


def s31(f):
    # Scenario 31 summary (src/s31_test.py): per-seed paired dL7 and the cluster-bootstrap interval in d["ci"]["dL7"]
    d = json.load(open(output_or_reference(f)))
    lo, hi = d["ci"]["dL7"]
    return sum(d["dL7"]) / len(d["dL7"]), lo, hi


def headroom(f):
    return tuple(json.load(open(output_or_reference(f)))["H"])


ROWS = [  # (panel, label, value source, style)
    ("a", r"RA$+$RD vs.\ RA (C2)", boot("_boot_doppler_check.json"), "main"),
    ("a", r"RA$+$DA vs.\ RA (not chosen)", boot("_boot_nonselected_RADA_vs_RA.json"), ""),
    ("a", r"RA$+$DA$+$RD vs.\ RA$+$RD", boot("_boot_threemaps_vs_RD.json"), ""),
    ("a", r"Scenario~31: RA$+$RD vs.\ RA", s31("_s31fix_test_summary.json"), ""),
    ("a", r"vs.\ feedback-free tracker$^{\dagger}$", boot("_boot_student_vs_ekf_no_doppler.json"), ""),
    ("a", r"vs.\ anchored tracker$^{\dagger}$", boot("_boot_student_vs_ekf_no_doppler_anchored.json"), ""),
    ("b", r"teacher's lead (headroom)", headroom("_boot_joint_R.json"), "ref"),
    ("b", r"logit KD, teacher 42 (C3)", boot("_boot_kd_logit.json"), "main"),
    ("b", r"$+$ feature", boot("_boot_kd_feat.json"), ""),
    ("b", r"$+$ temporal", boot("_boot_kd_full.json"), ""),
    ("b", r"logit KD, teacher 1", boot("_boot_w6_G1.json"), ""),
    ("b", r"logit KD, teacher 2", boot("_boot_w6_G2.json"), ""),
    ("b", r"concatenation teacher", boot("_boot_cckd_vs_nokd.json"), ""),
    ("b", r"enlarged gap (RA student)", boot("_boot_rakd_vs_RA.json"), ""),
    ("b", r"10 passes, V$+$R teacher", boot("_boot_w5_VR10.json"), ""),
    ("b", r"10 passes, radar teacher", boot("_boot_w5_R10.json"), ""),
]
HEAD = {"a": r"radar input, against the named arm", "b": r"distillation, against the undistilled student"}
if LETTERS:
    HEAD = {k: f"({k}) " + v for k, v in HEAD.items()}

XMIN, XMAX = -0.2, 0.9
LABW = 3.80                                  # cm reserved for row labels
PLOTW = WIDTH - LABW - 0.15
sx = PLOTW / (XMAX - XMIN)
X = lambda v: LABW + (v - XMIN) * sx
DY = 0.36

lines = [r"% Generated by figures/make_forest.py from the stored bootstrap results; do not edit by hand.",
         r"\begin{tikzpicture}[x=1cm, y=1cm, font=\footnotesize]"]
y, rows_y, panel, pan_y = 0.0, [], None, {}
for p, lab, (v, lo, hi), style in ROWS:
    if p != panel:
        if panel is not None:
            y -= 0.18
        lines.append(rf"\node[anchor=west, font=\footnotesize\itshape] at (0,{y:.3f}) {{{HEAD[p]}}};")
        y -= DY; panel = p
    col = "black!45" if style == "ref" else "black"
    lines.append(rf"\node[anchor=east, text={col}] at ({LABW - 0.08:.3f},{y:.3f}) {{{lab}}};")
    lines.append(rf"\draw[{col}, line width=0.8pt] ({X(lo):.3f},{y:.3f}) -- ({X(hi):.3f},{y:.3f});")
    mark = r"\fill" if style != "ref" else r"\fill"
    size = "1.9pt" if style == "main" else "1.4pt"
    lines.append(rf"{mark}[{col}] ({X(v):.3f},{y:.3f}) circle ({size});")
    rows_y.append(y); pan_y.setdefault(p, []).append(y); y -= DY
ybot = y + DY - 0.22
ytop = rows_y[0] + 0.2
last = list(pan_y)[-1]
for pp, ys in pan_y.items():  # zero line per panel, so it does not cross the panel headings
    y0, y1 = max(ys) + 0.2, (ybot if pp == last else min(ys) - 0.2)
    lines.append(rf"\draw[black!55, densely dashed, line width=0.5pt] ({X(0):.3f},{y0:.3f}) -- ({X(0):.3f},{y1:.3f});")
lines.append(rf"\draw[black!80, line width=0.5pt] ({X(XMIN):.3f},{ybot:.3f}) -- ({X(XMAX):.3f},{ybot:.3f});")
for t in (-0.2, 0.0, 0.2, 0.4, 0.6, 0.8):
    lines.append(rf"\draw[black!80] ({X(t):.3f},{ybot:.3f}) -- ++(0,-2.5pt) node[below, inner sep=2pt] {{${t:+.1f}$}};".replace("$+0.0$", "$0$"))
lines.append(rf"\node[anchor=north] at ({X((XMIN + XMAX) / 2):.3f},{ybot - 0.42:.3f}) {{loss reduction [dB]}};")
lines.append(r"\end{tikzpicture}")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
for p, lab, (v, lo, hi), style in ROWS:
    print(f"{p} {lab:40s} {v:+.3f} [{lo:+.3f}, {hi:+.3f}]")
print("height ~", round(-(ybot - 0.9), 2), "cm ->", OUT)
