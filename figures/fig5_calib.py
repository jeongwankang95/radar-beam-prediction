"""Fig. 5 data: mean beam-selection loss against top-1 accuracy for the nine predictors of Table II, with the
least-squares line and its pointwise 95% confidence band (t with 7 degrees of freedom, for this test set). Writes the
data-driven TikZ elements (band, line, points and std bars on both axes) in the figure's frame, x = ATop-1 - 36.4 pp and
y = dB - 0.22, to the given file; axes, ticks and labels were drawn by hand. The band and the line are the paper's; the paper places
the points and bars at the rounded entries of Table II, within 0.1 pp and 0.01 dB of the positions written here.
Usage: python figures/fig5_calib.py OUT.tex"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "analysis"))
import numpy as np
from scipy import stats
from paths import result, pow_test

X0, Y0 = 36.4, 0.22
XS = ["0.00", "0.52", "1.05", "1.58", "2.10", "2.62", "3.15", "3.67", "4.20", "4.73", "5.25", "5.77", "6.30", "6.83",
      "7.35", "7.88", "8.40", "8.93", "9.45", "9.98", "10.50"]
z = np.load(result("_pred_dump.npz")); OPT = z["OPT"]; POW = pow_test().astype(np.float64)
BEST = np.take_along_axis(POW, OPT[..., None], -1)[..., 0]
ARMS = ["RA only", "DA only", "RD only", "RA+DA", "RA+RD", "RA+DA+RD", "RA+RD+KD", "Vision-only", "Teacher"]
acc, los, asd, lsd = [], [], [], []
for arm in ARMS:
    P = [z[k] for k in z.files if k.startswith(arm + "::")]
    a = np.array([100 * (p == OPT).mean() for p in P])
    l = np.array([(-10 * np.log10(np.clip(np.take_along_axis(POW, p[..., None], -1)[..., 0] / BEST, 1e-6, None))).mean() for p in P])
    acc.append(a.mean()); los.append(l.mean()); asd.append(a.std(ddof=1)); lsd.append(l.std(ddof=1))
acc, los = np.array(acc), np.array(los)
n = len(acc); r = stats.linregress(acc, los); b, c = r.slope, r.intercept
s = np.sqrt(((los - (b * acc + c)) ** 2).sum() / (n - 2)); Sxx = ((acc - acc.mean()) ** 2).sum(); t = stats.t.ppf(0.975, n - 2)
hw = lambda x: t * s * np.sqrt(1 / n + (x - acc.mean()) ** 2 / Sxx)
yf = lambda x: b * (float(x) + X0) + c - Y0
L = ["% Generated by figures/fig5_calib.py: band, line, points and +-std bars of Fig. 5 (x = ATop-1 - 36.4, y = dB - 0.22)",
     r"\fill[gray!16] " + " -- ".join([f"({x},{yf(x) + hw(float(x) + X0):.3f})" for x in XS] +
                                      [f"({x},{yf(x) - hw(float(x) + X0):.3f})" for x in XS[::-1]]) + " -- cycle;",
     rf"\draw[thick] (0.00,{yf('0.00'):.3f}) -- (10.50,{yf('10.50'):.3f});"]
for arm, a, l, sa, sl in zip(ARMS, acc, los, asd, lsd):
    x, y = a - X0, l - Y0
    L += [f"% {arm}: ATop-1 {a:.2f} +- {sa:.2f} %, loss {l:.3f} +- {sl:.3f} dB",
          rf"\draw[eb] ({x - sa:.2f},{y:.3f}) -- ({x + sa:.2f},{y:.3f});", rf"\draw[eb] ({x:.2f},{y - sl:.3f}) -- ({x:.2f},{y + sl:.3f});",
          rf"\node[pt] at ({x:.2f},{y:.3f}) {{}};"]
open(sys.argv[1], "w").write("\n".join(L) + "\n")
print(f"slope {b:.4f} dB/pp, R2 {r.rvalue ** 2:.3f}; band half-width {hw(acc.mean()):.3f} at the centroid, "
      f"{hw(X0):.3f}/{hw(X0 + 10.5):.3f} at the plot edges -> {sys.argv[1]}")
