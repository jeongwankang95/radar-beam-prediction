r"""fig_lc.py OUT_TEX: learning curve of the reference RA+RD student (Sec. VII-B, supp. Table S13), written as plain TikZ
in the style of Fig. 4 (fig_style.tex: depl = deployed radar-only path; every series here is a deployed radar-only
student, so all are depl and differ by line pattern and marker, as in Fig. 4: solid filled circle = undistilled,
dashed open circle = logit KD from the vision-radar teacher, dotted open square = logit KD from a radar-only teacher).
(a) mean beam-selection loss against the number of training passes (nested subsets, log axis);
(b) the distillation gain (undistilled minus distilled loss) with its 95% cluster-bootstrap interval.
Data, read directly: results/analysis (else results/reference)/_boot_lc{10,20,45}_kd_vs_nokd.json and _boot_kd_logit.json (no KD and
vision-radar-teacher KD at 10/20/45/91 passes), _boot_w5_R{10,20}.json (radar-only teacher at 10/20 passes); the same
files numcheck reads for supp. Table S13 and Sec. VII-B."""
import json
import math
import sys

import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "analysis"))
from paths import output_or_reference
J = lambda f: json.load(open(output_or_reference(f)))
P = (10, 20, 45, 91)
FILES = {10: "_boot_lc10_kd_vs_nokd.json", 20: "_boot_lc20_kd_vs_nokd.json", 45: "_boot_lc45_kd_vs_nokd.json",
         91: "_boot_kd_logit.json"}
NOKD, KD, GAIN = {}, {}, {}
for p, f in FILES.items():
    d = J(f)
    NOKD[p], KD[p] = d["ref"]["mean_db"], d["new"]["mean_db"]
    g = d["deltas"]["dB recovered (ref-new)"]
    GAIN[p] = (g["point"], g["lo"], g["hi"])
RKD, RGAIN = {}, {}
for p in (10, 20):
    d = J(f"_boot_w5_R{p}.json")
    assert abs(d["ref"]["mean_db"] - NOKD[p]) < 1e-9          # same undistilled arm as the learning curve
    RKD[p] = d["new"]["mean_db"]
    g = d["deltas"]["dB recovered (ref-new)"]
    RGAIN[p] = (g["point"], g["lo"], g["hi"])

XW = 6.3                                    # cm from 10 to 91 passes (log axis), as Fig. 4's horizon width
HA, A0, A1 = 2.35, 0.40, 2.70               # panel (a): height [cm], loss range [dB]
HB, B0, B1 = 2.35, -0.15, 0.90              # panel (b): height [cm], gain range [dB]
YB, YA = 0.0, 3.05                          # panel bottoms [cm]
DX = 0.11                                   # horizontal offset between the two teachers' gains in (b) [cm]
PAD = 0.30                                  # axis margin beyond the first and last tick [cm]


def x(p): return XW * (math.log10(p) - 1.0) / (math.log10(91) - 1.0)
def ya(v): return YA + HA * (v - A0) / (A1 - A0)
def yb(v): return YB + HB * (v - B0) / (B1 - B0)


L = [r"""% Fig.: learning curve of the reference student with and without distillation. Generated by fig_lc.py (do not edit by hand).
\begin{tikzpicture}[font=\scriptsize, x=1cm, y=1cm,
  ln/.style={line width=0.8pt, line join=round},
  st/.style={ln, draw=depl, line width=0.95pt},
  kd/.style={ln, draw=depl, dash pattern=on 2.2pt off 1.4pt},
  rk/.style={ln, draw=depl, dash pattern=on 0.6pt off 1.2pt, line cap=round},
  st mark/.style={circle, fill=depl, draw=depl, inner sep=0pt, minimum size=3.6pt},
  kd mark/.style={circle, fill=white, draw=depl, line width=0.6pt, inner sep=0pt, minimum size=3.6pt},
  rk mark/.style={rectangle, fill=white, draw=depl, line width=0.6pt, inner sep=0pt, minimum size=3.3pt},
  eb/.style={draw=depl, line width=0.5pt},
  grid/.style={black!12, line width=0.3pt}, ax/.style={black!70, line width=0.4pt}, zero/.style={black!45, line width=0.45pt}]"""]
for f, ticks, fmt, y0, h in ((ya, (0.5, 1.0, 1.5, 2.0, 2.5), "{:.1f}", YA, HA), (yb, (0.0, 0.2, 0.4, 0.6, 0.8), "{:.1f}", YB, HB)):
    for v in ticks:
        L.append(f"\\draw[grid] ({-PAD:.2f},{f(v):.3f}) -- ({XW + PAD:.2f},{f(v):.3f}); \\node[anchor=east,inner sep=2pt] at ({-PAD:.2f},{f(v):.3f}) {{${fmt.format(v)}$}};")
    L.append(f"\\draw[ax] ({-PAD:.2f},{y0:.3f}) -- ({-PAD:.2f},{y0 + h:.3f}); \\draw[ax] ({-PAD:.2f},{y0:.3f}) -- ({XW + PAD:.2f},{y0:.3f});")
L.append(f"\\draw[zero] ({-PAD:.2f},{yb(0):.3f}) -- ({XW + PAD:.2f},{yb(0):.3f});")
for p in P:
    L.append(f"\\draw[ax] ({x(p):.3f},{YA:.3f}) -- ++(0,-2pt); \\draw[ax] ({x(p):.3f},{YB:.3f}) -- ++(0,-2pt); \\node[anchor=north,inner sep=3pt] at ({x(p):.3f},{YB:.3f}) {{${p}$}};")
L.append(f"\\node[anchor=south west,inner sep=1pt] at ({0.05 - PAD:.2f},{YA + HA + 0.02:.3f}) {{(a) mean beam-selection loss [dB]}};")
L.append(f"\\node[anchor=south west,inner sep=1pt] at ({0.05 - PAD:.2f},{YB + HB + 0.02:.3f}) {{(b) gain from distillation [dB], $95\\%$ interval}};")
L.append(f"\\node[anchor=north,inner sep=1pt] at ({XW / 2:.2f},{YB - 0.42:.3f}) {{training passes (nested subsets of the $91$)}};")
# panel (a): lines, then markers
L.append("\\draw[st] " + " -- ".join(f"({x(p):.3f},{ya(NOKD[p]):.3f})" for p in P) + ";")
L.append("\\draw[kd] " + " -- ".join(f"({x(p):.3f},{ya(KD[p]):.3f})" for p in P) + ";")
L.append("\\draw[rk] " + " -- ".join(f"({x(p):.3f},{ya(RKD[p]):.3f})" for p in (10, 20)) + ";")
L.append(" ".join(f"\\node[st mark] at ({x(p):.3f},{ya(NOKD[p]):.3f}) {{}};" for p in P))
L.append(" ".join(f"\\node[kd mark] at ({x(p):.3f},{ya(KD[p]):.3f}) {{}};" for p in P))
L.append(" ".join(f"\\node[rk mark] at ({x(p):.3f},{ya(RKD[p]):.3f}) {{}};" for p in (10, 20)))
# panel (b): intervals with caps, then markers; the vision-radar teacher's gains left of each tick, the radar-only right
for gains, dx, mk in ((GAIN, -DX, "kd mark"), (RGAIN, DX, "rk mark")):
    for p, (pt, lo, hi) in gains.items():
        xx = x(p) + (dx if p in RGAIN else 0)
        L.append(f"\\draw[eb] ({xx:.3f},{yb(lo):.3f}) -- ({xx:.3f},{yb(hi):.3f}); "
                 f"\\draw[eb] ({xx - 0.05:.3f},{yb(lo):.3f}) -- ({xx + 0.05:.3f},{yb(lo):.3f}); "
                 f"\\draw[eb] ({xx - 0.05:.3f},{yb(hi):.3f}) -- ({xx + 0.05:.3f},{yb(hi):.3f}); "
                 f"\\node[{mk}] at ({xx:.3f},{yb(pt):.3f}) {{}};")
# legend: two rows above panel (a)
LEG = [("st", "st mark", "RA$+$RD student, no KD", -0.85, 0.98), ("kd", "kd mark", "logit KD, vision--radar teacher", 2.55, 0.98),
       ("rk", "rk mark", "logit KD, radar-only teacher", 2.55, 0.58)]
for sty, mk, lab, x0, dy in LEG:
    y = YA + HA + dy
    L.append(f"\\draw[{sty}] ({x0:.2f},{y:.3f}) -- ({x0 + 0.42:.2f},{y:.3f}); \\node[{mk}] at ({x0 + 0.21:.2f},{y:.3f}) {{}}; \\node[anchor=west,inner sep=1pt] at ({x0 + 0.48:.2f},{y:.3f}) {{{lab}}};")
L.append("\\end{tikzpicture}")
open(sys.argv[1], "w").write("\n".join(L) + "\n")
print("wrote", sys.argv[1], len(L), "lines")
print("no KD", {p: round(v, 3) for p, v in NOKD.items()}, "KD", {p: round(v, 3) for p, v in KD.items()}, "radar KD", {p: round(v, 3) for p, v in RKD.items()})
print("gain", {p: tuple(round(u, 3) for u in g) for p, g in GAIN.items()}, "radar gain", {p: tuple(round(u, 3) for u in g) for p, g in RGAIN.items()})
