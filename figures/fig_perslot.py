r"""fig_perslot.py OUT_TEX: per-slot top-1 accuracy and mean beam-selection loss over the horizon (Scenario 9 test, ten
seeds per arm), written as plain TikZ in the style of Figs. 1-3 (fig_style.tex: depl = deployed radar-only path,
trn = training-only elements; grays otherwise). Data: results/analysis/perslot.json, computed by figures/perslot.py from
results/_pred_dump.npz and the measured sweep powers (reproduces Tables I-II and supp. Table S14).
Encodings are redundant (color + line pattern + marker) so no series depends on color alone; palette separation was
checked in OKLab under CVD simulation (min dE 19.6, normal 22.2)."""
import json
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "analysis"))
from paths import output_or_reference
P = json.load(open(output_or_reference("perslot.json")))
XU = 1.05                                   # cm per slot
HA, A0, A1 = 2.35, 35.0, 48.0               # panel (a): height [cm], accuracy range [%]
HB, B0, B1 = 2.35, 0.30, 1.15               # panel (b): height [cm], loss range [dB]
YB, YA = 0.0, 3.05                          # panel bottoms [cm]
ARMS = [  # key in perslot.json, style, marker, legend label
    ("RA only",     "ra", "ra mark", "range--angle only"),
    ("Vision-only", "vi", "vi mark", "vision-only"),
    ("Teacher",     "te", "te mark", "vision--radar teacher"),
    ("RA+RD+KD",    "kd", "kd mark", "RA$+$RD, logit KD"),
    ("RA+RD",       "st", "st mark", "RA$+$RD student"),
]
def ya(v): return YA + HA * (v - A0) / (A1 - A0)
def yb(v): return YB + HB * (v - B0) / (B1 - B0)
L = [r"""% Fig.: per-slot accuracy and loss over the horizon. Generated by fig_perslot.py (do not edit by hand).
\begin{tikzpicture}[font=\scriptsize, x=1cm, y=1cm,
  ln/.style={line width=0.8pt, line join=round},
  st/.style={ln, draw=depl, line width=0.95pt},
  kd/.style={ln, draw=depl, dash pattern=on 2.2pt off 1.4pt},
  te/.style={ln, draw=trn, dash pattern=on 2.2pt off 1.4pt},
  vi/.style={ln, draw=black!90},
  ra/.style={ln, draw=black!35},
  st mark/.style={circle, fill=depl, draw=depl, inner sep=0pt, minimum size=3.6pt},
  kd mark/.style={circle, fill=white, draw=depl, line width=0.6pt, inner sep=0pt, minimum size=3.6pt},
  te mark/.style={regular polygon, regular polygon sides=3, fill=trn, inner sep=0pt, minimum size=4.6pt},
  vi mark/.style={rectangle, fill=black!90, inner sep=0pt, minimum size=3.0pt},
  ra mark/.style={diamond, fill=black!35, inner sep=0pt, minimum size=4.2pt},
  grid/.style={black!12, line width=0.3pt}, ax/.style={black!70, line width=0.4pt}]"""]
# grids, axes and tick labels
for lo, hi, ticks, f, fmt, y0, h in ((A0, A1, (36, 40, 44, 48), ya, "{:g}", YA, HA), (B0, B1, (0.4, 0.6, 0.8, 1.0), yb, "{:.1f}", YB, HB)):
    for v in ticks:
        L.append(f"\\draw[grid] (0,{f(v):.3f}) -- ({6 * XU:.2f},{f(v):.3f}); \\node[anchor=east,inner sep=2pt] at (0,{f(v):.3f}) {{${fmt.format(v)}$}};")
    L.append(f"\\draw[ax] (0,{y0:.3f}) -- (0,{y0 + h:.3f}); \\draw[ax] (0,{y0:.3f}) -- ({6 * XU:.2f},{y0:.3f});")
for k in range(7):
    lab = "$t$" if k == 0 else f"$t{{+}}{k}$"
    L.append(f"\\draw[ax] ({k * XU:.2f},{YA:.3f}) -- ++(0,-2pt); \\draw[ax] ({k * XU:.2f},{YB:.3f}) -- ++(0,-2pt); \\node[anchor=north,inner sep=3pt] at ({k * XU:.2f},{YB:.3f}) {{{lab}}};")
L.append(f"\\node[anchor=south west,inner sep=1pt] at (0.05,{YA + HA + 0.02:.3f}) {{(a) top-$1$ accuracy [\\%]}};")
L.append(f"\\node[anchor=south west,inner sep=1pt] at (0.05,{YB + HB + 0.02:.3f}) {{(b) mean beam-selection loss [dB]}};")
L.append(f"\\node[anchor=north,inner sep=1pt] at ({3 * XU:.2f},{YB - 0.42:.3f}) {{slot of the horizon}};")
# series: lines then markers, panel by panel
for key, sty, mk, _ in ARMS:
    a, b = P[key]["acc_mean"], P[key]["db_mean"]
    L.append(f"\\draw[{sty}] " + " -- ".join(f"({k * XU:.2f},{ya(v):.3f})" for k, v in enumerate(a)) + ";")
    L.append(f"\\draw[{sty}] " + " -- ".join(f"({k * XU:.2f},{yb(v):.3f})" for k, v in enumerate(b)) + ";")
for key, sty, mk, _ in ARMS:
    a, b = P[key]["acc_mean"], P[key]["db_mean"]
    L.append(" ".join(f"\\node[{mk}] at ({k * XU:.2f},{ya(v):.3f}) {{}};" for k, v in enumerate(a)))
    L.append(" ".join(f"\\node[{mk}] at ({k * XU:.2f},{yb(v):.3f}) {{}};" for k, v in enumerate(b)))
# legend: two rows above panel (a), so the figure fits the column width
LEG = [("te", "te mark", "teacher (V$+$R)"), ("vi", "vi mark", "vision-only"), ("st", "st mark", "RA$+$RD student"),
       ("kd", "kd mark", "same, logit KD"), ("ra", "ra mark", "range--angle only")]
for i, (sty, mk, lab) in enumerate(LEG):
    x0 = (0.0, 2.35, 4.55)[i % 3] - 0.55; y = YA + HA + (0.98 if i < 3 else 0.58)
    L.append(f"\\draw[{sty}] ({x0:.2f},{y:.3f}) -- ({x0 + 0.42:.2f},{y:.3f}); \\node[{mk}] at ({x0 + 0.21:.2f},{y:.3f}) {{}}; \\node[anchor=west,inner sep=1pt] at ({x0 + 0.48:.2f},{y:.3f}) {{{lab}}};")
L.append("\\end{tikzpicture}")
open(sys.argv[1], "w").write("\n".join(L) + "\n")
print("wrote", sys.argv[1], len(L), "lines")
